/// Ciudades de un país (ISO). Si no se conoce, lista vacía.
pub fn cities_of(iso: &str) -> &'static [&'static str] {
    COUNTRIES
        .iter()
        .find(|c| c.iso.eq_ignore_ascii_case(iso))
        .map(|c| c.cities)
        .unwrap_or(&[])
}
